"""Fast Videomancer program simulation: GHDL -> Verilog -> Verilator.

Same inputs and outputs as the SDK's VHDL image tester (same image scaling,
BT.601 conversion, register mapping, raster and capture), roughly 1000x
faster, and it can capture several consecutive frames.

  fastsim.py simulate <program_dir> [--image IMG] [--set KEY=V ...]
             [--video-mode 1080p2997] [--decimation 4]
             [--warmup-frames 2] [--capture-frames 1]
             [--output out.png | out.gif]

The per-program simulator binary is cached in build/fastsim/<name>-<hash>/ and
rebuilt only when a source file, the config or the harness changes.
Run with the bundled Python: `source tools/env.sh` first.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "videomancer-sdk/tools/vhdl-image-tester"))

from vhdl_image_tester.cli import _load_registers  # noqa: E402
from vhdl_image_tester.core.config import (  # noqa: E402
    ABI_REG_VIDEO_TIMING, SIM_WARMUP_FRAMES, resolve_video_settings)
from vhdl_image_tester.core.image_converter import (  # noqa: E402
    prepare_image, rgb_to_yuv10, yuv10_to_rgb)
from vhdl_image_tester.core.program_loader import load_program  # noqa: E402
from vhdl_image_tester.core.sim_runner import (  # noqa: E402
    _ordered_program_sources, _ordered_sdk_sources)

BUILD_ROOT = ROOT / "build/fastsim"
SB_PRIMITIVES = sorted((ROOT / "videomancer-sdk/third_party/SiliconBlue/rtl").glob("sb_*.vhd"))

_WRAPPER = """\
-- Generated by tools/fastsim/fastsim.py: flat ports for Verilator.
library ieee;
use ieee.std_logic_1164.all;
library work;
use work.core_pkg.all;
use work.video_stream_pkg.all;

entity vm_fastsim_top is
    port (
        clk : in std_logic;
{reg_ports}
        yi, ui, vi : in std_logic_vector(9 downto 0);
        avid_i, hsync_n_i, vsync_n_i, field_n_i : in std_logic;
        yo, uo, vo : out std_logic_vector(9 downto 0);
        avid_o, hsync_n_o, vsync_n_o, field_n_o : out std_logic
    );
end entity;

architecture rtl of vm_fastsim_top is
    signal s_regs : t_spi_ram;
    signal s_in, s_out : t_video_stream_yuv444_30b;
begin
{reg_assigns}
    s_in.y <= yi; s_in.u <= ui; s_in.v <= vi;
    s_in.avid <= avid_i; s_in.hsync_n <= hsync_n_i;
    s_in.vsync_n <= vsync_n_i; s_in.field_n <= field_n_i;
    dut : entity work.program_top
        port map (clk => clk, registers_in => s_regs, data_in => s_in, data_out => s_out);
    yo <= s_out.y; uo <= s_out.u; vo <= s_out.v;
    avid_o <= s_out.avid; hsync_n_o <= s_out.hsync_n;
    vsync_n_o <= s_out.vsync_n; field_n_o <= s_out.field_n;
end architecture;
"""


def _sources(program_dir: Path, config: str) -> list[Path]:
    prog = _ordered_program_sources(program_dir)
    uses_sb = any("SB_" in p.read_text(errors="ignore") for p in prog)
    return _ordered_sdk_sources(config, "yuv444_30b") + (SB_PRIMITIVES if uses_sb else []) + prog


def build(program_dir: Path, config: str, log=print) -> Path:
    """Return the cached simulator binary for this program, building it if needed."""
    srcs = _sources(program_dir, config)
    h = hashlib.sha256(config.encode())
    for p in srcs + [HERE / "harness.cpp", Path(__file__)]:
        h.update(p.name.encode())
        h.update(p.read_bytes())
    out = BUILD_ROOT / f"{program_dir.name}-{config}-{h.hexdigest()[:12]}"
    exe = out / "obj_dir/Vvm_fastsim_top"
    if exe.exists():
        return exe

    t0 = time.time()
    out.mkdir(parents=True, exist_ok=True)
    wrapper = out / "vm_fastsim_top.vhd"
    wrapper.write_text(_WRAPPER.format(
        reg_ports="\n".join(f"        r{i} : in std_logic_vector(9 downto 0);" for i in range(32)),
        reg_assigns="\n".join(f"    s_regs({i}) <= r{i};" for i in range(32)),
    ))
    verilog = out / "design.v"
    files = " ".join(str(p) for p in srcs + [wrapper])
    script = (f"ghdl --std=08 {files} -e vm_fastsim_top; "
              f"proc; flatten; memory -nomap; opt -fast; write_verilog -noattr {verilog}")
    _run(["yosys", "-q", "-m", "ghdl", "-l", str(out / "yosys.log"), "-p", script], out, "yosys")
    log(f"[fastsim] exported Verilog ({time.time() - t0:.1f}s)")

    _run(["verilator", "--cc", "--exe", "--build", "-O3", "-Wno-fatal", "-Wno-lint",
          "-Wno-style", "--x-assign", "fast", "--x-initial", "fast",
          "--top-module", "vm_fastsim_top", str(verilog), str(HERE / "harness.cpp"),
          "-CFLAGS", "-O2", "-j", str(os.cpu_count() or 4)], out, "verilator")
    log(f"[fastsim] built simulator ({time.time() - t0:.1f}s total) -> {out.name}")
    return exe


def _run(cmd, cwd, name):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        tail = "\n".join((r.stdout + r.stderr).splitlines()[-30:])
        raise RuntimeError(f"{name} failed:\n{tail}")


# Real raster totals for progressive standards (CEA-861):
# (pixels per line, lines per frame, hsync clocks, vsync lines). The default
# compact raster (SDK tester: +64 clocks, +8 lines) is far shorter, which
# breaks programs that use the blanking time (e.g. czartroniks/bishop draws
# during the previous line) or size things from the video timing ID.
REAL_TIMING = {
    "480p": (858, 525, 62, 6),
    "576p": (864, 625, 64, 5),
    "720p60": (1650, 750, 40, 5), "720p5994": (1650, 750, 40, 5),
    "720p50": (1980, 750, 40, 5),
    "1080p30": (2200, 1125, 44, 5), "1080p2997": (2200, 1125, 44, 5),
    "1080p25": (2640, 1125, 44, 5),
    "1080p24": (2750, 1125, 44, 5), "1080p2398": (2750, 1125, 44, 5),
}


# Frames per second of each progressive standard: the device's frame clock.
# (1080p tops out at 30: the HD pixel clock is 74.25 MHz.)
FRAME_RATES = {
    "480p": 59.94, "576p": 50.0,
    "720p60": 60.0, "720p5994": 59.94, "720p50": 50.0,
    "1080p30": 30.0, "1080p2997": 29.97, "1080p25": 25.0,
    "1080p24": 24.0, "1080p2398": 23.98,
}


def timing_args(video_mode: str, real_timing: bool) -> list[str]:
    """Harness arguments for a real raster (full resolution only)."""
    if not real_timing:
        return []
    if video_mode not in REAL_TIMING:
        raise ValueError(f"no real timing for {video_mode}; choose one of {sorted(REAL_TIMING)}")
    h_total, v_total, hsync, vsync = REAL_TIMING[video_mode]
    vs = resolve_video_settings(video_mode, 1)
    return ["--timing", str(h_total - vs.sim_width), str(v_total - vs.sim_height),
            str(hsync), str(vsync)]


def uses_timing_id(program_dir: Path) -> bool:
    """Does the program read the video timing ID (registers_in(8))?"""
    return any("registers_in(8)" in p.read_text(errors="ignore")
               for p in Path(program_dir).glob("*.vhd"))


def simulate(program_dir: Path, image: Image.Image, values: dict[str, int],
             video_mode: str = "1080p2997", decimation: int = 4,
             warmup_frames: int = SIM_WARMUP_FRAMES, capture_frames: int = 1,
             log=print, real_timing: bool = False) -> list[Image.Image]:
    """Run the program on *image*; return one RGB image per captured frame.

    real_timing: feed the standard's true resolution and blanking
    (decimation is ignored), as the device would see it.
    """
    program_dir = program_dir.resolve()
    program = load_program(program_dir.name, program_dir.parent)
    if real_timing:
        decimation = 1
    vs = resolve_video_settings(video_mode, decimation)
    exe = build(program_dir, vs.fpga_config, log)

    regs = program.build_register_array(values)
    regs[ABI_REG_VIDEO_TIMING] = vs.timing_id
    yuv = rgb_to_yuv10(prepare_image(image, vs.sim_width, vs.sim_height))
    w, h = vs.sim_width, vs.sim_height

    work = exe.parent.parent
    inp, outp = work / "in.raw", work / "out.raw"
    yuv.astype("<u2").tofile(inp)
    r = subprocess.run([str(exe), str(inp), str(outp), str(w), str(h),
                        str(int(vs.is_interlaced)), str(warmup_frames), str(capture_frames),
                        ",".join(str(v) for v in regs), *timing_args(video_mode, real_timing)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"simulator failed: {r.stderr.strip()}")
    log(r.stderr.strip())
    frames = np.fromfile(outp, dtype="<u2").reshape(capture_frames, h, w, 3)
    return [yuv10_to_rgb(f) for f in frames]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("simulate", help="simulate a program on an image")
    s.add_argument("program_dir", type=Path)
    s.add_argument("--image", type=Path, default=ROOT / "test-images/shapes.png")
    s.add_argument("--set", action="append", default=[], metavar="KEY=V")
    s.add_argument("--preset")
    s.add_argument("--video-mode", default="1080p2997")
    s.add_argument("--decimation", type=int, default=4)
    s.add_argument("--warmup-frames", type=int, default=SIM_WARMUP_FRAMES)
    s.add_argument("--capture-frames", type=int, default=1)
    s.add_argument("--real-timing", action="store_true",
                   help="true resolution and blanking of --video-mode (e.g. 480p)")
    s.add_argument("--fps", type=float, default=12, help="GIF playback rate")
    s.add_argument("--output", type=Path)
    a = ap.parse_args()

    prog_dir = a.program_dir.resolve()
    program = load_program(prog_dir.name, prog_dir.parent)
    values = _load_registers(program, a.set, None, a.preset)
    frames = simulate(prog_dir, Image.open(a.image), values, a.video_mode, a.decimation,
                      a.warmup_frames, a.capture_frames, real_timing=a.real_timing)
    out = a.output or Path(f"{prog_dir.name}_fast.{'gif' if len(frames) > 1 else 'png'}")
    if out.suffix.lower() == ".gif":
        frames[0].save(out, save_all=True, append_images=frames[1:],
                       duration=round(1000 / a.fps), loop=0)
    else:
        frames[-1].save(out)
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
